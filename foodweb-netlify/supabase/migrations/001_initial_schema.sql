-- Atomic server-side order creation: trusts neither client prices nor client totals.
create or replace function public.create_foodweb_order(
  p_user_id uuid,
  p_contact_name text,
  p_contact_phone text,
  p_event_date date,
  p_special_request text,
  p_allergy_text text,
  p_items jsonb
) returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  v_ref text;
  v_order_id bigint;
  v_total bigint := 0;
  v_item record;
  v_menu public.menus%rowtype;
  v_count integer := 0;
begin
  if length(trim(coalesce(p_contact_name,''))) < 2 or length(trim(coalesce(p_contact_name,''))) > 60 then
    raise exception 'Nama pemesan tidak valid';
  end if;
  if length(regexp_replace(coalesce(p_contact_phone,''), '\D', '', 'g')) not between 8 and 15 then
    raise exception 'Nomor telepon tidak valid';
  end if;
  if p_event_date <= (now() at time zone 'Asia/Jakarta')::date or p_event_date > (now() at time zone 'Asia/Jakarta')::date + 90 then
    raise exception 'Tanggal pesanan harus antara besok dan 90 hari ke depan';
  end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) < 1 or jsonb_array_length(p_items) > 20 then
    raise exception 'Keranjang tidak valid';
  end if;
  for v_item in select * from jsonb_to_recordset(p_items) as x(menu_id bigint, qty integer) loop
    v_count := v_count + 1;
    if v_item.qty not between 5 and 500 then raise exception 'Jumlah porsi harus 5-500'; end if;
    select * into v_menu from public.menus where id=v_item.menu_id and active=true;
    if not found then raise exception 'Menu tidak ditemukan'; end if;
    v_total := v_total + (v_menu.price::bigint * v_item.qty::bigint);
  end loop;
  if v_count = 0 then raise exception 'Keranjang kosong'; end if;
  v_ref := 'FW-' || upper(substr(encode(gen_random_bytes(8),'hex'),1,6));
  insert into public.orders(ref,user_id,contact_name,contact_phone,event_date,special_request,allergy_text,total)
  values(v_ref,p_user_id,trim(p_contact_name),regexp_replace(p_contact_phone,'\D','','g'),p_event_date,
    left(coalesce(p_special_request,''),500),left(coalesce(p_allergy_text,''),200),v_total)
  returning id into v_order_id;
  for v_item in select * from jsonb_to_recordset(p_items) as x(menu_id bigint, qty integer) loop
    select * into v_menu from public.menus where id=v_item.menu_id and active=true;
    insert into public.order_items(order_id,menu_id,menu_name,unit_price,qty)
    values(v_order_id,v_menu.id,v_menu.name,v_menu.price,v_item.qty);
  end loop;
  insert into public.payments(order_id) values(v_order_id);
  return jsonb_build_object('id',v_order_id,'ref',v_ref,'total',v_total);
end;
$$;
revoke all on function public.create_foodweb_order(uuid,text,text,date,text,text,jsonb) from public, anon, authenticated;
grant execute on function public.create_foodweb_order(uuid,text,text,date,text,text,jsonb) to service_role;

