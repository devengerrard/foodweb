-- Food Web / Catering Oma migration to Supabase PostgreSQL.
-- Run in Supabase SQL Editor. Never commit real credentials or user data.
create extension if not exists pgcrypto;

create table if not exists public.users (
  id uuid primary key default gen_random_uuid(),
  username text not null unique,
  password_hash text not null,
  full_name text not null,
  phone text not null,
  role text not null default 'customer' check (role in ('customer','admin')),
  created_at timestamptz not null default now(),
  constraint username_format check (username ~ '^[A-Za-z0-9_]{3,30}$')
);
create unique index if not exists users_username_lower_uq on public.users (lower(username));

create table if not exists public.preferences (
  user_id uuid primary key references public.users(id) on delete cascade,
  has_allergy boolean not null default false,
  allergy_text text not null default '',
  tastes text[] not null default '{}',
  diets text[] not null default '{}',
  updated_at timestamptz not null default now()
);

create table if not exists public.menus (
  id bigint generated by default as identity primary key,
  name text not null,
  description text not null,
  price integer not null check (price > 0),
  taste text not null check (taste in ('asin','manis','pedas')),
  diets text[] not null default '{}',
  allergens text not null default '',
  allergen_known boolean not null default true,
  active boolean not null default true
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  ref text not null unique,
  user_id uuid not null references public.users(id),
  contact_name text not null,
  contact_phone text not null,
  event_date date not null,
  special_request text not null default '',
  allergy_text text not null default '',
  total bigint not null check (total > 0),
  created_at timestamptz not null default now()
);
create index if not exists orders_user_created_idx on public.orders(user_id, created_at desc);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  menu_id bigint not null references public.menus(id),
  menu_name text not null,
  unit_price integer not null check (unit_price > 0),
  qty integer not null check (qty between 5 and 500)
);

create table if not exists public.payments (
  id bigint generated by default as identity primary key,
  order_id bigint not null unique references public.orders(id) on delete cascade,
  method text not null default 'QRIS_SIMULASI',
  status text not null default 'awaiting_payment'
    check (status in ('awaiting_payment','awaiting_verification','paid','rejected')),
  payer_note text not null default '',
  confirmed_at timestamptz,
  verified_by uuid references public.users(id),
  verified_at timestamptz,
  admin_note text not null default ''
);

create table if not exists public.audit_log (
  id bigint generated by default as identity primary key,
  actor_id uuid references public.users(id),
  action text not null,
  detail text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.login_attempts (
  id bigint generated by default as identity primary key,
  username_key text not null,
  ip_key text not null,
  succeeded boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists login_attempts_lookup_idx on public.login_attempts(username_key, ip_key, created_at desc);

create unique index if not exists menus_name_uq on public.menus(name);

